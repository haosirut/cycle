"""
Интеграция с DeepSeek API через openai-клиент.
"""

import logging
from openai import AsyncOpenAI

from bot.config import config

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "Ты — эксперт по биохакингу и управлению человеческой производительностью. "
    "Анализируй данные через призму 5 измерений: Энергия, Ясность, Вовлечённость, "
    "Напряжение, Восстановление.\n\n"
    "Каждое измерение оценивается от 1 до 10:\n"
    "- Энергия: общий физический ресурсный уровень организма\n"
    "- Ясность: качество работы префронтальной коры (фокус, решения, рабочая память)\n"
    "- Вовлечённость: агентность, мотивация, ощущение субъектности\n"
    "- Напряжение: аллостатическая нагрузка (кумулятивное давление внешних и внутренних факторов)\n"
    "- Восстановление: качество регенерации (сон, отдых, глубина перезагрузки)\n\n"
    "Readiness Score = Восстановление×0.30 + Энергия×0.25 + Ясность×0.20 "
    "+ Вовлечённость×0.15 + (10−Напряжение)×0.10\n\n"
    "Типы событий и их критичные параметры:\n"
    "- presentation (Выступление): Ясность≥7, Вовлечённость≥7\n"
    "- physical (Физ. нагрузка): Энергия≥6, Восстановление≥6\n"
    "- strategic (Стратег. решение): Ясность≥8, Напряжение≤4\n"
    "- routine (Рутина): Энергия≥5\n"
    "- negotiation (Переговоры): Вовлечённость≥6, Энергия≥6\n\n"
    "Для каждого дня с событием:\n"
    "1. Оцени Readiness Score и тренд (растёт/стабилен/падает)\n"
    "2. Сопоставь профиль готовности с типом события\n"
    "3. Дай рекомендацию по подготовке:\n"
    "   - Сон: сколько часов, когда лечь\n"
    "   - Питание: что добавить/убрать\n"
    "   - Активность: тип и интенсивность\n"
    "   - Когнитивная подготовка: что сделать для ясности\n"
    "   - Стресс-менеджмент: техники снижения напряжения\n\n"
    "Если прогноз RED FLAG (Readiness < 4 или критичный параметр ниже минимума) — "
    "предложи перенос или снижение нагрузки.\n\n"
    "Формат вывода для каждого дня:\n"
    "ДД.ММ — Событие — Readiness: X.X — Прогноз — Рекомендация"
)


class DeepSeekService:
    """Сервис для работы с DeepSeek API."""

    def __init__(self):
        self.client = AsyncOpenAI(
            api_key=config.DS_API_KEY,
            base_url=config.DS_BASE_URL,
        )

    async def predict(self, user_prompt: str) -> str:
        """
        Отправляет запрос к DeepSeek и возвращает текстовый прогноз.

        :param user_prompt: Сформированный промпт с историей пользователя.
        :return: Текстовый ответ модели.
        """
        try:
            response = await self.client.chat.completions.create(
                model=config.DS_MODEL,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_prompt},
                ],
                temperature=0.7,
                max_tokens=2500,
            )
            result = response.choices[0].message.content
            logger.info("Получен ответ от DeepSeek (длина=%d)", len(result))
            return result
        except Exception as e:
            logger.error("Ошибка при запросе к DeepSeek: %s", e)
            raise


# Глобальный экземпляр сервиса
deepseek_service = DeepSeekService()
